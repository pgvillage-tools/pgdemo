func TemplateNames() []string {
	names := make([]string, len(Templates))
	for i, t := range Templates {
		names[i] = t.Name
	}
	return names
}

func TemplateByName(name string) *Template {
	for _, t := range Templates {
		if t.Name == name {
			return t
		}
	}
	return nil
}

// EstimateRows returns a human readable row overview for base size n.
func EstimateRows(t *Template, n int) string {
	parts := make([]string, 0, len(t.Tables))
	total := 0
	for _, tb := range t.Tables {
		c := tb.Rows(n)
		total += c
		name := tb.Name
		if tb.Schema != "" {
			name = tb.Schema + "." + tb.Name
		}
		parts = append(parts, fmt.Sprintf("%s: %d", name, c))
	}
	return strings.Join(parts, " · ") + fmt.Sprintf("\nTotal: %d rows", total)
}

func fk(table, col, ref string) string {
	return fmt.Sprintf("ALTER TABLE {s}.%s ADD CONSTRAINT %s_%s_fk FOREIGN KEY (%s) REFERENCES {s}.%s (id)",
		table, table, col, col, ref)
}

func idx(table string, cols ...string) string {
	return fmt.Sprintf("CREATE INDEX ON {s}.%s (%s)", table, strings.Join(cols, ", "))
}

