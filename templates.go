func hr() *Template {
	nDept := func(n int) int { return len(departments) }
	nEmp := func(n int) int { return max(20, n) }
	nProj := func(n int) int { return max(5, n/10) }
	perEmp := func(n int) int { return min(2, nProj(n)) }
	nEP := func(n int) int { return nEmp(n) * perEmp(n) }

	return &Template{
		Name:        "HR",
		Description: "Departments, employees (with managers), projects and project assignments.",
		Tables: []Table{
			{
				Name: "departments", HasID: true,
				DDL: idCol + `,
    name     text NOT NULL UNIQUE,
    location text NOT NULL`,
				Cols: []string{"id", "name", "location"},
				Rows: nDept,
				Row: func(g *Gen, k int) []any {
					d := departments[k-1]
					return []any{k, d[0], d[1]}
				},
			},
			{
				Name: "employees", HasID: true,
				DDL: idCol + `,
    first_name    text NOT NULL,
    last_name     text NOT NULL,
    email         text NOT NULL UNIQUE,
    hire_date     date NOT NULL,
    job_title     text NOT NULL,
    salary        numeric(10,2) NOT NULL,
    department_id integer NOT NULL,
    manager_id    integer`,
				FKs: []string{
					fk("employees", "department_id", "departments"),
					fk("employees", "manager_id", "employees"),
				},
				Indexes: []string{idx("employees", "department_id"), idx("employees", "manager_id")},
				Cols:    []string{"id", "first_name", "last_name", "email", "hire_date", "job_title", "salary", "department_id", "manager_id"},
				Rows:    nEmp,
				Row: func(g *Gen, k int) []any {
					f, l := g.FirstName(), g.LastName()
					var manager any // first employees are department heads without a manager
					title := g.Pick(jobTitles)
					dept := g.Int(1, nDept(g.N))
					if k <= nDept(g.N) {
						title, dept = "Head of department", k
					} else {
						manager = g.Int(1, min(k-1, max(nDept(g.N), g.N/10)))
					}
					return []any{k, f, l, Email(f, l, k, "company.example"), g.Date(2005, 2025),
						title, g.Money(2800, 9500), dept, manager}
				},
			},
			{
				Name: "projects", HasID: true,
				DDL: idCol + `,
    name       text NOT NULL,
    start_date date NOT NULL,
    end_date   date,
    budget     numeric(12,2)`,
				Cols: []string{"id", "name", "start_date", "end_date", "budget"},
				Rows: nProj,
				Row: func(g *Gen, k int) []any {
					start := g.Date(2020, 2025)
					var end any
					if g.Chance(0.7) {
						end = start.AddDate(0, 0, g.Int(30, 700))
					}
					return []any{k, fmt.Sprintf("%s %d", g.Pick(projectNames), k), start, end, g.Money(10000, 500000)}
				},
			},
			{
				Name: "employee_projects",
				DDL: `employee_id    integer NOT NULL,
    project_id     integer NOT NULL,
    role           text NOT NULL,
    hours_per_week integer NOT NULL,
    PRIMARY KEY (employee_id, project_id)`,
				FKs: []string{
					fk("employee_projects", "employee_id", "employees"),
					fk("employee_projects", "project_id", "projects"),
				},
				Indexes: []string{idx("employee_projects", "project_id")},
				Cols:    []string{"employee_id", "project_id", "role", "hours_per_week"},
				Rows:    nEP,
				Row: func(g *Gen, k int) []any {
					ne, np := nEmp(g.N), nProj(g.N)
					e := (k-1)%ne + 1
					j := (k - 1) / ne // 0..perEmp-1, so (e*3+j) gives distinct projects per employee
					return []any{e, (e*3+j)%np + 1, g.Pick(projectRoles), g.Int(4, 40)}
				},
			},
		},
		Views: []string{
			`CREATE VIEW {s}.department_overview AS
SELECT d.id, d.name, d.location,
       count(e.id) AS employees,
       round(avg(e.salary), 2) AS avg_salary
FROM {s}.departments d
LEFT JOIN {s}.employees e ON e.department_id = d.id
GROUP BY d.id`,
		},
	}
}

