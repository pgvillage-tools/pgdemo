func webshop() *Template {
	nCat := func(n int) int { return len(categoryNames) }
	nProd := func(n int) int { return max(20, n/2) }
	nCust := func(n int) int { return max(10, n) }
	nOrd := func(n int) int { return nCust(n) * 3 }
	nItem := func(n int) int { return nOrd(n) * 3 }

	return &Template{
		Name:        "Webshop",
		Description: "Customers, categories, products, orders and order lines.",
		Tables: []Table{
			{
				Name: "categories", HasID: true,
				DDL: idCol + `,
    name        text NOT NULL UNIQUE,
    description text`,
				Cols: []string{"id", "name", "description"},
				Rows: nCat,
				Row: func(g *Gen, k int) []any {
					name := categoryNames[k-1]
					return []any{k, name, "All kinds of " + strings.ToLower(name)}
				},
			},
			{
				Name: "products", HasID: true,
				DDL: idCol + `,
    category_id integer NOT NULL,
    name        text NOT NULL,
    price       numeric(10,2) NOT NULL CHECK (price >= 0),
    stock       integer NOT NULL DEFAULT 0,
    created_at  timestamptz NOT NULL DEFAULT now()`,
				FKs:     []string{fk("products", "category_id", "categories")},
				Indexes: []string{idx("products", "category_id")},
				Cols:    []string{"id", "category_id", "name", "price", "stock", "created_at"},
				Rows:    nProd,
				Row: func(g *Gen, k int) []any {
					price := g.Money(2, 750)
					g.prices = append(g.prices, price)
					name := fmt.Sprintf("%s %s %d", g.Pick(productAdjectives), g.Pick(productNouns), g.Int(100, 999))
					return []any{k, g.Int(1, nCat(g.N)), name, price, g.Int(0, 500), g.Timestamp(2018, 2025)}
				},
			},
			{
				Name: "customers", HasID: true,
				DDL: idCol + `,
    first_name text NOT NULL,
    last_name  text NOT NULL,
    email      text NOT NULL UNIQUE,
    phone      text,
    city       text,
    created_at timestamptz NOT NULL DEFAULT now()`,
				Indexes: []string{idx("customers", "last_name")},
				Cols:    []string{"id", "first_name", "last_name", "email", "phone", "city", "created_at"},
				Rows:    nCust,
				Row: func(g *Gen, k int) []any {
					f, l := g.FirstName(), g.LastName()
					return []any{k, f, l, Email(f, l, k, "example.com"), g.Phone(), g.City(), g.Timestamp(2018, 2025)}
				},
			},
			{
				Name: "orders", HasID: true,
				DDL: idCol + `,
    customer_id integer NOT NULL,
    order_date  timestamptz NOT NULL DEFAULT now(),
    status      text NOT NULL CHECK (status IN ('new','paid','shipped','delivered','cancelled'))`,
				FKs:     []string{fk("orders", "customer_id", "customers")},
				Indexes: []string{idx("orders", "customer_id"), idx("orders", "order_date")},
				Cols:    []string{"id", "customer_id", "order_date", "status"},
				Rows:    nOrd,
				Row: func(g *Gen, k int) []any {
					return []any{k, g.Int(1, nCust(g.N)), g.Timestamp(2022, 2025), g.Pick(orderStatuses)}
				},
			},
			{
				Name: "order_items", HasID: true,
				DDL: idCol + `,
    order_id   integer NOT NULL,
    product_id integer NOT NULL,
    quantity   integer NOT NULL CHECK (quantity > 0),
    unit_price numeric(10,2) NOT NULL`,
				FKs:     []string{fk("order_items", "order_id", "orders"), fk("order_items", "product_id", "products")},
				Indexes: []string{idx("order_items", "order_id"), idx("order_items", "product_id")},
				Cols:    []string{"id", "order_id", "product_id", "quantity", "unit_price"},
				Rows:    nItem,
				Row: func(g *Gen, k int) []any {
					// Every order gets at least one line, the rest are spread randomly.
					order := k
					if k > nOrd(g.N) {
						order = g.Int(1, nOrd(g.N))
					}
					p := g.Int(1, nProd(g.N))
					price := g.Money(2, 750)
					if p <= len(g.prices) {
						price = g.prices[p-1]
					}
					return []any{k, order, p, g.Int(1, 5), price}
				},
			},
		},
		Views: []string{
			`CREATE VIEW {s}.order_totals AS
SELECT o.id AS order_id, o.customer_id, o.order_date, o.status,
       count(oi.id) AS lines,
       coalesce(sum(oi.quantity * oi.unit_price), 0) AS total
FROM {s}.orders o
LEFT JOIN {s}.order_items oi ON oi.order_id = o.id
GROUP BY o.id`,
			`CREATE VIEW {s}.customer_revenue AS
SELECT c.id AS customer_id, c.first_name, c.last_name, c.city,
       count(DISTINCT o.id) AS orders,
       coalesce(sum(oi.quantity * oi.unit_price), 0) AS revenue
FROM {s}.customers c
LEFT JOIN {s}.orders o ON o.customer_id = c.id AND o.status <> 'cancelled'
LEFT JOIN {s}.order_items oi ON oi.order_id = o.id
GROUP BY c.id`,
		},
	}
}

