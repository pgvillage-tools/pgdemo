// Table describes one demo table: its DDL and how to generate its rows.
// "{s}" in any SQL string is replaced by the quoted schema name, "{s_hr}" by
// the quoted name of the extra schema with suffix "hr" (see Template.Schemas).
type Table struct {
	Name    string
	Schema  string   // "" = the main schema, otherwise the suffix of an extra schema
	DDL     string   // column definitions (inside CREATE TABLE ( ... ))
	HasID   bool     // has an identity column "id" whose sequence must be reset after loading
	FKs     []string // ALTER TABLE ... ADD CONSTRAINT ... statements
	Indexes []string
	Cols    []string                  // column order used by Row
	Rows    func(n int) int           // number of rows for base size n
	Row     func(g *Gen, k int) []any // values for row k (1-based)
}

type Template struct {
	Name        string
	Description string
	Schemas     []string // suffixes of extra schemas: "hr" makes <name>_hr next to <name>
	MainSuffix  string   // when set, the main schema is <name>_<MainSuffix> instead of <name>
	Tables      []Table  // in creation / load order (parents first)
	Views       []string
	Locale      string   // country of the personal values ("" = NL), see locale.go
	Renames     []Rename // column renames at the end (local column names)
	Extensions  []string // extensions the database must have, e.g. "postgis" (checked before anything is made)
}

// schemaRef is the placeholder for a table's schema: {s} or {s_<suffix>}.
func schemaRef(suffix string) string {
	if suffix == "" {
		return "{s}"
	}
	return "{s_" + suffix + "}"
}

// fks builds a foreign key between tables that may be in different schemas.
func fks(schema, table, name, cols, refSchema, ref, refCols, extra string) string {
	s := fmt.Sprintf("ALTER TABLE %s.%s ADD CONSTRAINT %s FOREIGN KEY (%s) REFERENCES %s.%s (%s)",
		schemaRef(schema), table, name, cols, schemaRef(refSchema), ref, refCols)
	if extra != "" {
		s += " " + extra
	}
	return s
}

// idxs creates an index on a table in schema (suffix).
func idxs(schema, table string, cols ...string) string {
	return fmt.Sprintf("CREATE INDEX ON %s.%s (%s)", schemaRef(schema), table, strings.Join(cols, ", "))
}

// uidxs creates a unique index on a table in schema (suffix).
func uidxs(schema, table string, cols ...string) string {
	return fmt.Sprintf("CREATE UNIQUE INDEX ON %s.%s (%s)", schemaRef(schema), table, strings.Join(cols, ", "))
}

